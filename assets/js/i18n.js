document.addEventListener('DOMContentLoaded', () => {
    const defaultLang = localStorage.getItem('site_lang') || 'fr';
    setLanguage(defaultLang);

    const langToggleBtn = document.getElementById('lang-toggle');
    if (langToggleBtn) {
        langToggleBtn.addEventListener('click', (e) => {
            e.preventDefault();
            const currentLang = localStorage.getItem('site_lang') || 'fr';
            const newLang = currentLang === 'fr' ? 'en' : 'fr';
            setLanguage(newLang);
        });
    }
});

function setLanguage(lang) {
    localStorage.setItem('site_lang', lang);

    // Translate Texts
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            // If element has HTML children we want to preserve (like icons inside anchors),
            // we only replace the text nodes. For simplicity, if it's a direct text replacement:
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.setAttribute('placeholder', translations[lang][key]);
            } else {
                // Safe replacement keeping existing icon if present
                const icon = el.querySelector('i');
                if (icon) {
                    el.innerHTML = translations[lang][key] + ' ';
                    el.appendChild(icon);
                } else {
                    el.innerHTML = translations[lang][key];
                }
            }
        }
    });
}
